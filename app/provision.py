"""Environment provisioner: renders a per-company decoy container (compose override) and its proxy listener.
Run on the HOST via scripts/provision.py; the control plane never gets Docker access (a Docker socket is root on the host)."""
import re
PORT_RANGE = range(8100, 8120)   # must match the proxy's published range in docker-compose.yml

def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:32] or "env"

def service_name(slug: str) -> str: return f"decoy-{slug}"

def render_compose(slug: str) -> str:
    n = service_name(slug)
    return f"""# generated by scripts/provision.py for environment '{slug}'. Do not edit.
services:
  {n}:
    build: .
    command: ["uvicorn", "app.decoy:app", "--host", "0.0.0.0", "--port", "8000"]
    environment:
      DATABASE_URL: "postgresql+psycopg://hiab_ingest:${{HIAB_INGEST_DB_PASSWORD}}@db:5432/hiab"
      HIAB_SKIP_MIGRATE: "1"
      REDIS_URL: "redis://:${{HIAB_REDIS_PASSWORD}}@redis:6379/0"
      HIAB_ENV_ID: "{slug}"
    security_opt: ["no-new-privileges:true"]
    cap_drop: [ALL]
    read_only: true
    tmpfs: [/tmp]
    mem_limit: 256m
    cpus: 0.5
    pids_limit: 100
    depends_on: {{migrate: {{condition: service_completed_successfully}}, redis: {{condition: service_healthy}}}}
    networks: [decoy, db_ingest]
"""

def render_nginx(slug: str, port: int) -> str:
    n = service_name(slug)
    # variable proxy_pass: nginx resolves the name at request time, so a stopped container cannot break proxy startup
    return f"""# generated for environment '{slug}'
server {{
  listen {port};
  location / {{ set $up http://{n}:8000; proxy_pass $up; }}
}}
"""
